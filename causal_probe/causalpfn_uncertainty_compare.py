"""Head-to-head: FADO bootstrap-sigma vs CausalPFN's OWN posterior uncertainty.

The uncertainty section of the paper asks a defensive question: FADO's
per-output reliability signal is a *row-bootstrap* std of a single checkpoint
(``causal_probe/bootstrap_uncertainty.py``). One can object that a
bootstrap std is a crude, model-agnostic device — a "real" Bayesian causal
method emits a calibrated posterior directly. CausalPFN (Balazadeh et al.,
NeurIPS 2025) is exactly such a method: it is a PFN whose forward pass emits a
*predictive posterior* per query, so it exposes a native per-estimate
uncertainty (unlike LiNGAM, DML, SHAP, etc., which give a point estimate only).

This script compares the two uncertainties head to head on the SAME held-out
synthetic SCMs, using the SAME per-column protocol both methods' point
estimates are produced under, and asks of each: *does the uncertainty track the
error?* Two summaries per regime:

  * Spearman(uncertainty, |estimate - tau_true|)  — rank-correlation of the
    reliability flag with the realised absolute error. Higher = the uncertainty
    is a better "don't trust this" signal.
  * selective-prediction gain: mean |error| on the low-uncertainty half minus
    the high-uncertainty half. A well-calibrated flag makes the low-half error
    substantially smaller.

--------------------------------------------------------------------------
HOW CausalPFN's NATIVE UNCERTAINTY IS EXTRACTED (the load-bearing choice)
--------------------------------------------------------------------------
CausalPFN's point estimate in this repo (``run_baseline.causalpfn_tau`` /
``comparator_suite._causalpfn_col``) uses the per-column protocol: median-
binarize covariate i into a binary treatment t, treat the other p-1 columns as
covariates, fit an estimator on (X_rest, t, y), take the ATE, and rescale to the
probe's reporting scale via ``2 * ate * std_X_i / (gap * std_y)``.

To extract the uncertainty *consistently* with that point estimate we keep the
identical binarize + rescale protocol, but use CausalPFN's ``CATEEstimator``
(which exposes the posterior-CI API; the ``ATEEstimator`` used for the point
estimate does not). CausalPFN draws ``n_samples`` posterior samples of the
per-row potential outcomes and forms an ATE-posterior sample vector internally
(``causal_estimator._estimate_ate_cate_CI`` builds ``ate_samples`` and returns
a quantile CI on it). We take the returned 95% ATE CI ``[lo, hi]`` and convert
its half-width to a posterior sigma,

    sigma_ate = (hi - lo) / (2 * 1.96),

then apply the SAME point-estimate rescaling to put the uncertainty on the same
per-sigma-X reporting scale as tau:

    sigma_col = 2 * sigma_ate * std_X_i / (gap * std_y).

This is the direct analog of FADO's bootstrap-std-of-tau: a per-column scalar,
same units as the estimate, larger = less reliable. The point estimate reported
alongside it is CATEEstimator's ATE (mean of per-row CATE), rescaled identically
-- so the (estimate, uncertainty) pair comes from ONE fitted CausalPFN posterior,
which is the fair thing to correlate against |estimate - tau_true|.

--------------------------------------------------------------------------
CAVEAT (state it in the docstring and the JSON — do not bury it)
--------------------------------------------------------------------------
The per-column
median-cut protocol is OUT OF DISTRIBUTION for CausalPFN: in its training prior
the treatment is generated by a propensity model conditional on covariates
(ignorability holds by construction), whereas a median-cut on a covariate is a
deterministic, non-confounded, conditioning-violating "treatment", and
descendants of the chosen column sit in the conditioning set. So this compares
UNCERTAINTY-TRACKING UNDER OUR EVAL SETUP, not on CausalPFN's home turf
(IHDP/ACIC/Lalonde designated-treatment CATE). It is a defensive comparison
for the paper's uncertainty section — "even its own posterior, run in our
setting, does not track error better than FADO's bootstrap sigma" — NOT a
claim about CausalPFN's intrinsic calibration on the tasks it was designed for.
The caveat is duplicated into the output JSON under ``config.caveat``.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np

# 95% CI half-width -> Gaussian sigma.
_Z_95 = 1.959963984540054

# The three held-out regimes the uncertainty section reports on.
_DEFAULT_REGIMES = "linear:laplace,hidden:laplace,mlp:laplace"


# ---------------------------------------------------------------------------
# SCM construction (delegates to the shared eval builder so the SCM stream
# matches the model-side eval and bootstrap_uncertainty.py exactly).
# ---------------------------------------------------------------------------

def _build_scms(regime: str, p: int, n_scms: int, rng: np.random.Generator) -> list:
    """Build n_scms SCMs of ``scm_type:noise``, e.g. ``linear:laplace``."""
    from causal_probe.eval import _make_eval_scm
    scm_type, noise = regime.split(":")
    return [_make_eval_scm(scm_type, p, rng, noise=noise) for _ in range(n_scms)]


def _sample_scm(scm, n_rows: int, rng: np.random.Generator):
    """Draw one (X, y, tau) sample; matches bootstrap_uncertainty.py seeding."""
    from causal_probe.eval import _EVAL_SCM_SEED_LO, _EVAL_SCM_SEED_HI
    samp = scm.sample(
        n=n_rows,
        rng=np.random.default_rng(rng.integers(_EVAL_SCM_SEED_LO, _EVAL_SCM_SEED_HI)),
    )
    return (
        samp.X.astype(np.float64),
        samp.y.astype(np.float64),
        np.asarray(samp.tau, dtype=np.float64),
    )


# ---------------------------------------------------------------------------
# FADO bootstrap-sigma (imported wholesale from bootstrap_uncertainty.py so the
# reliability signal is byte-for-byte the same as the paper's FADO number).
# ---------------------------------------------------------------------------

def _fado_estimate_and_sigma(model, X, y, n_boot, rng, device):
    """(estimate, sigma) per column for FADO on one (X, y).

    estimate = bootstrap-mean tau_hat; sigma = bootstrap std (the exact signal
    from bootstrap_uncertainty.evaluate_regime).
    """
    from causal_probe.bootstrap_uncertainty import _bootstrap_preds
    boot = _bootstrap_preds(model, X, y, n_boot, rng, device)  # (n_boot, p)
    return boot.mean(axis=0), boot.std(axis=0, ddof=1)


# ---------------------------------------------------------------------------
# CausalPFN native posterior uncertainty (see module docstring for rationale).
# ---------------------------------------------------------------------------

def _causalpfn_estimate_and_sigma(
    X, y, *, device, cache_dir, n_samples, alpha=0.05,
):
    """(estimate, sigma) per column from CausalPFN's own predictive posterior.

    Same median-binarize + gap-rescale per-column protocol as the point-estimate
    baseline (run_baseline.causalpfn_tau); uncertainty = ATE posterior-CI
    half-width / z, rescaled identically. Columns with degenerate splits or a
    failed fit yield NaN in both outputs.
    """
    import os
    from causalpfn import CATEEstimator  # lazy — not imported on the dry path

    if cache_dir is None:
        cache_dir = os.environ.get("CAUSALPFN_CACHE_DIR")

    p = X.shape[1]
    std_y = float(np.std(y).clip(min=1e-9))
    est = np.full(p, np.nan, dtype=np.float64)
    sig = np.full(p, np.nan, dtype=np.float64)

    for i in range(p):
        x_i = X[:, i]
        med = float(np.median(x_i))
        t = (x_i > med).astype(np.int64)
        if t.sum() < 5 or (1 - t).sum() < 5:
            continue
        gap = float(x_i[t == 1].mean() - x_i[t == 0].mean())
        if gap < 1e-9:
            continue
        std_X_i = float(np.std(x_i).clip(min=1e-9))
        X_rest = np.delete(X, i, axis=1).astype(np.float64)
        scale = 2.0 * std_X_i / (gap * std_y)  # shared reporting-scale factor
        try:
            kwargs = {"device": device}
            if cache_dir is not None:
                kwargs["cache_dir"] = cache_dir
            estimator = CATEEstimator(**kwargs)
            estimator.fit(X_rest, t, y.astype(np.float64))
            # Point estimate: mean per-row CATE (== ATE), rescaled like the
            # published causalpfn point baseline.
            ate = float(estimator.estimate_ate(X_rest))
            # Native posterior uncertainty on the ATE: 95% CI half-width / z.
            ci = estimator._estimate_ate_cate_CI(
                X_rest, alpha=alpha, n_samples=n_samples,
            )
            lo = float(np.asarray(ci["ate_lower_bound"]).reshape(-1)[0])
            hi = float(np.asarray(ci["ate_upper_bound"]).reshape(-1)[0])
            sigma_ate = (hi - lo) / (2.0 * _Z_95)
        except Exception as e:
            print(f"    feature {i}: CausalPFN CATEEstimator failed: {e}", flush=True)
            continue
        est[i] = ate * scale
        sig[i] = abs(sigma_ate) * scale

    return est, sig


# ---------------------------------------------------------------------------
# Tracking metrics (shared for both methods).
# ---------------------------------------------------------------------------

def _tracking_metrics(sigma: np.ndarray, err: np.ndarray) -> dict:
    """Does the uncertainty track error? Spearman + selective-prediction gain.

    sigma, err : flat 1-D arrays over all (scm, feature) pairs. Non-finite
    entries in either are dropped pairwise.
    """
    from scipy.stats import spearmanr, pearsonr

    mask = np.isfinite(sigma) & np.isfinite(err)
    n = int(mask.sum())
    out = {
        "n_pairs": n,
        "spearman_sigma_err": float("nan"),
        "pearson_sigma_err": float("nan"),
        "mean_abs_err": float("nan"),
        "mean_sigma": float("nan"),
        "err_low_uncert_half": float("nan"),
        "err_high_uncert_half": float("nan"),
        "selective_gain": float("nan"),
    }
    if n < 4:
        return out
    s = sigma[mask]
    e = err[mask]
    out["mean_abs_err"] = float(e.mean())
    out["mean_sigma"] = float(s.mean())
    if s.std() > 0:
        out["spearman_sigma_err"] = float(spearmanr(s, e)[0])
        out["pearson_sigma_err"] = float(pearsonr(s, e)[0])
    # selective prediction: split at the median sigma; low half should have
    # smaller error if the flag is calibrated.
    thr = float(np.median(s))
    low = e[s <= thr]
    high = e[s > thr]
    if low.size and high.size:
        out["err_low_uncert_half"] = float(low.mean())
        out["err_high_uncert_half"] = float(high.mean())
        out["selective_gain"] = float(high.mean() - low.mean())
    return out


# ---------------------------------------------------------------------------
# Per-regime driver.
# ---------------------------------------------------------------------------

def evaluate_regime(
    regime, scms, *, n_rows, n_boot, rng, device,
    fado_model, causalpfn_kwargs,
):
    """Run BOTH methods on the same SCM samples; return a metrics dict per
    method plus the paired count."""
    fado_sig, fado_err = [], []
    cpfn_sig, cpfn_err = [], []
    n_fado_fail = n_cpfn_fail = 0

    for k, scm in enumerate(scms):
        X, y, tau = _sample_scm(scm, n_rows, rng)

        # FADO
        try:
            f_est, f_sig = _fado_estimate_and_sigma(
                fado_model, X, y, n_boot,
                np.random.default_rng(rng.integers(0, 2**31)), device,
            )
            fado_sig.append(f_sig)
            fado_err.append(np.abs(f_est - tau))
        except Exception as e:
            print(f"  [{regime}] SCM {k}: FADO failed: {e}", flush=True)
            n_fado_fail += 1

        # CausalPFN (native posterior)
        try:
            c_est, c_sig = _causalpfn_estimate_and_sigma(
                X, y, **causalpfn_kwargs,
            )
            cpfn_sig.append(c_sig)
            cpfn_err.append(np.abs(c_est - tau))
        except Exception as e:
            print(f"  [{regime}] SCM {k}: CausalPFN failed: {e}", flush=True)
            n_cpfn_fail += 1

    fado = _tracking_metrics(
        np.concatenate(fado_sig) if fado_sig else np.array([]),
        np.concatenate(fado_err) if fado_err else np.array([]),
    )
    cpfn = _tracking_metrics(
        np.concatenate(cpfn_sig) if cpfn_sig else np.array([]),
        np.concatenate(cpfn_err) if cpfn_err else np.array([]),
    )
    fado["n_scms_failed"] = n_fado_fail
    cpfn["n_scms_failed"] = n_cpfn_fail
    return {"regime": regime, "n_scms": len(scms),
            "fado_bootstrap_sigma": fado, "causalpfn_native": cpfn}


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------

_CAVEAT = (
    "Per-column median-cut protocol is OUT OF DISTRIBUTION for CausalPFN "
    "(its prior generates the treatment via a propensity model conditional on "
    "covariates; a median-cut is deterministic, non-confounded, and violates "
    "conditioning). This compares uncertainty-tracking UNDER OUR EVAL SETUP, "
    "not on CausalPFN's home turf (IHDP/ACIC/Lalonde designated-treatment "
    "CATE). Defensive comparison for the uncertainty section only."
)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--ckpt", default=None,
                    help="FADO checkpoint (required unless --dry-run).")
    ap.add_argument("--device", default="cuda",
                    help="torch device for FADO and CausalPFN.")
    ap.add_argument("--seed", type=int, default=100)
    ap.add_argument("--n-scms", type=int, default=100)
    ap.add_argument("--n-rows", type=int, default=512)
    ap.add_argument("--n-boot", type=int, default=200,
                    help="FADO row-bootstrap resamples.")
    ap.add_argument("--n-posterior-samples", type=int, default=1000,
                    help="CausalPFN posterior draws for the ATE CI.")
    ap.add_argument("--p", type=int, default=5)
    ap.add_argument("--regimes", default=_DEFAULT_REGIMES,
                    help="comma list of scm_type:noise regimes.")
    ap.add_argument("--cache-dir", default=None,
                    help="CausalPFN checkpoint cache (else CAUSALPFN_CACHE_DIR).")
    ap.add_argument(
        "--out",
        default="causal_probe/results/causalpfn_uncertainty_compare.json",
    )
    ap.add_argument("--dry-run", action="store_true",
                    help="Build SCMs, print counts, exit 0 without loading the "
                         "ckpt / touching the GPU / importing causalpfn.")
    args = ap.parse_args()

    regimes = [r.strip() for r in args.regimes.split(",") if r.strip()]
    rng = np.random.default_rng(args.seed)

    # Build SCMs first (cheap, CPU-only, no ckpt / causalpfn needed).
    scms_by_regime = {}
    for reg in regimes:
        scms_by_regime[reg] = _build_scms(reg, args.p, args.n_scms, rng)

    if args.dry_run:
        print("[dry-run] SCMs built per regime (no ckpt / GPU / causalpfn):")
        total = 0
        for reg, scms in scms_by_regime.items():
            # sanity: one CPU sample so shapes are exercised
            X, y, tau = _sample_scm(scms[0], min(64, args.n_rows), rng)
            total += len(scms)
            print(f"  {reg:<18} n_scms={len(scms):<4} "
                  f"sample X={X.shape} y={y.shape} tau={tau.shape}")
        print(f"[dry-run] total SCMs: {total}")
        print(f"[dry-run] FADO ckpt would be: {args.ckpt}")
        print(f"[dry-run] device would be: {args.device}")
        print("[dry-run] OK (causalpfn NOT imported, no GPU touched)")
        return

    if args.ckpt is None:
        ap.error("--ckpt is required unless --dry-run")

    from causal_probe.eval import _load_model
    print(f"Loading FADO ckpt {args.ckpt} on {args.device} ...", flush=True)
    fado_model = _load_model(args.ckpt, device=args.device)
    print(f"FADO row-bootstrap B={args.n_boot}; CausalPFN posterior "
          f"n_samples={args.n_posterior_samples}; {args.n_scms} SCMs/regime\n",
          flush=True)

    causalpfn_kwargs = dict(
        device=args.device, cache_dir=args.cache_dir,
        n_samples=args.n_posterior_samples,
    )

    results = {}
    for reg in regimes:
        print(f"[regime] {reg} ...", flush=True)
        results[reg] = evaluate_regime(
            reg, scms_by_regime[reg],
            n_rows=args.n_rows, n_boot=args.n_boot, rng=rng, device=args.device,
            fado_model=fado_model, causalpfn_kwargs=causalpfn_kwargs,
        )

    # Console summary table.
    print(f"\n{'regime':<18}{'method':<24}{'rho(sig,err)':>13}"
          f"{'sel.gain':>10}{'err_lo':>9}{'err_hi':>9}{'n':>7}")
    for reg, r in results.items():
        for key, label in (("fado_bootstrap_sigma", "FADO bootstrap-sigma"),
                           ("causalpfn_native", "CausalPFN native")):
            m = r[key]
            print(f"{reg:<18}{label:<24}"
                  f"{m['spearman_sigma_err']:>13.3f}"
                  f"{m['selective_gain']:>10.4f}"
                  f"{m['err_low_uncert_half']:>9.4f}"
                  f"{m['err_high_uncert_half']:>9.4f}"
                  f"{m['n_pairs']:>7}")

    Path(args.out).parent.mkdir(parents=True, exist_ok=True)
    payload = {
        "results": results,
        "config": {
            "ckpt": args.ckpt, "device": args.device, "seed": args.seed,
            "n_scms": args.n_scms, "n_rows": args.n_rows, "n_boot": args.n_boot,
            "n_posterior_samples": args.n_posterior_samples, "p": args.p,
            "regimes": regimes,
            "fado_uncertainty": "row-bootstrap std of a single checkpoint "
                                "(bootstrap_uncertainty.py)",
            "causalpfn_uncertainty": "ATE 95% posterior-CI half-width / 1.96, "
                                     "rescaled 2*std_X/(gap*std_y); from "
                                     "CATEEstimator._estimate_ate_cate_CI",
            "caveat": _CAVEAT,
        },
    }
    with open(args.out, "w") as f:
        json.dump(payload, f, indent=2)
    print(f"\nwrote {args.out}")


if __name__ == "__main__":
    main()
