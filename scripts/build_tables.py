    failed = []
    for fn in ALL_BUILDERS:
        print(f"--- {fn.__name__}")
        try:
            fn()
        except Exception as e:
            print(f"  FAIL: {type(e).__name__}: {e}")
            failed.append(fn.__name__)
    if failed:
        print(f"{len(failed)} builder(s) failed: {', '.join(failed)}")
        sys.exit(1)


