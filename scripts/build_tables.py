def build_seed_robust() -> None:
    # Foundation probe (fix-100k mixture heavy) seeds 0/1/2 evaluated on
    # linear non-Gaussian heavy at p=5, n=500. Seed 0 reuses the canonical
    # eval_main_p5_50k.json (the headline eval for that ckpt).
    p5 = [_load(RESULTS / "eval_main_p5_50k.json")["random"]["pearson"]["model"]]
    p5 += [_load(RESULTS / f"eval_main_p5_100k_mixture_heavy_seed{i}.json")["random"]["pearson"]["model"]
           for i in (1, 2)]

    def _stats(vals: list[float]) -> tuple[float, float]:
        a = np.array(vals)
        return float(a.mean()), float(a.std(ddof=1)) if len(a) > 1 else 0.0

    m5, s5 = _stats(p5)

    def _row(label, vals, mean, std):
        cells = [label] + [(f"${v:.3f}$" if v is not None else "—") for v in vals]
        cells.append(f"${mean:.3f} \\pm {std:.3f}$")
        return " & ".join(cells) + " \\\\"

    body = (
        "\\begin{tabular}{lrrrr}\n"
        "\\toprule\n"
        "Scale & Seed 0 & Seed 1 & Seed 2 & mean $\\pm$ std \\\\\n"
        "\\midrule\n"
        + _row("$p{=}5$", p5, m5, s5) + "\n"
        "\\bottomrule\n"
        "\\end{tabular}\n"
    )
    _write("seed_robust", body, "tab:seed-robust")


