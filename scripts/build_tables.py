def build_sachs() -> None:
    from scipy.stats import pearsonr
    rows = []
    for label, tag in SACHS_ROWS:
        z = np.load(BOOT / f"{tag}.npz", allow_pickle=True)
        pred = z["pred"]; true = z["true"]
        marg = z["marginal"]; multi = z["multivariate"]
        n = pred.shape[0]
        ppt = pearsonr(pred.flatten(), true.flatten())[0]
        pmt = pearsonr(marg.flatten(), true.flatten())[0]
        pvt = pearsonr(multi.flatten(), true.flatten())[0]
        rng = np.random.default_rng(BOOT_SEED)
        bp, bm, bv, bd = (np.empty(BOOT_B) for _ in range(4))
        for b in range(BOOT_B):
            idx = rng.integers(0, n, n)
            bp[b] = pearsonr(pred[idx].flatten(), true[idx].flatten())[0]
            bm[b] = pearsonr(marg[idx].flatten(), true[idx].flatten())[0]
            bv[b] = pearsonr(multi[idx].flatten(), true[idx].flatten())[0]
            bd[b] = bp[b] - bm[b]
        cells = [
            label,
            _f3sub(ppt, np.percentile(bp, 2.5), np.percentile(bp, 97.5)),
            _f3sub(ppt - pmt, np.percentile(bd, 2.5), np.percentile(bd, 97.5), sig=True),
            _f3sub(pmt, np.percentile(bm, 2.5), np.percentile(bm, 97.5)),
            _f3sub(pvt, np.percentile(bv, 2.5), np.percentile(bv, 97.5)),
        ]
        rows.append(" & ".join(cells) + " \\\\")

    body = (
        "\\begin{tabular}{l r r r r}\n"
        "\\toprule\n"
        "Variant        & FADO & $\\Delta$ vs Marginal corr. & Marginal corr. & Multivariate regression \\\\\n"
        "\\midrule\n"
        + "\n".join(rows) + "\n"
        "\\bottomrule\n"
        "\\end{tabular}\n"
    )
    _write("sachs_ckpts", body, "tab:sachs-ckpts")


